use darpc_protocol::{
    Architecture, ComponentVersion, Frame, Hello, Message, PROTOCOL_VERSION_1_0, VersionRange,
    decode_frame, encode_frame,
};

fn hello_frame() -> Frame {
    Frame::new(
        0x1234,
        0x7856_3412,
        Message::Hello(Hello {
            protocol_versions: VersionRange {
                min: PROTOCOL_VERSION_1_0,
                max: PROTOCOL_VERSION_1_0,
            },
            dll_instance_id: [
                0x00, 0x01, 0x02, 0x03, 0x04, 0x05, 0x06, 0x07, 0x08, 0x09, 0x0a, 0x0b, 0x0c, 0x0d,
                0x0e, 0x0f,
            ],
            process_id: 0x1122_3344,
            process_creation_time: 0x0102_0304_0506_0708,
            architecture: Architecture::X86,
            dll_version: ComponentVersion {
                major: 0,
                minor: 1,
                patch: 0,
            },
            executable_fingerprint: [
                0xa0, 0xa1, 0xa2, 0xa3, 0xa4, 0xa5, 0xa6, 0xa7, 0xa8, 0xa9, 0xaa, 0xab, 0xac, 0xad,
                0xae, 0xaf, 0xb0, 0xb1, 0xb2, 0xb3, 0xb4, 0xb5, 0xb6, 0xb7, 0xb8, 0xb9, 0xba, 0xbb,
                0xbc, 0xbd, 0xbe, 0xbf,
            ],
            client_version: 741,
        }),
    )
}

const HELLO_FRAME_BYTES: [u8; 95] = [
    0x44, 0x52, 0x50, 0x43, // magic: DRPC
    0x01, 0x00, // frame version
    0x01, 0x00, // Hello
    0x34, 0x12, // sequence
    0x00, 0x00, // flags
    0x12, 0x34, 0x56, 0x78, // sender tick
    0x4b, 0x00, 0x00, 0x00, // payload length: 75
    0x00, 0x01, 0x00, 0x01, // supported protocol versions: 1.0 through 1.0
    0x00, 0x01, 0x02, 0x03, 0x04, 0x05, 0x06, 0x07, // DLL instance ID
    0x08, 0x09, 0x0a, 0x0b, 0x0c, 0x0d, 0x0e, 0x0f, 0x44, 0x33, 0x22, 0x11, // process ID
    0x08, 0x07, 0x06, 0x05, 0x04, 0x03, 0x02, 0x01, // process creation time
    0x01, // x86
    0x00, 0x00, 0x01, 0x00, 0x00, 0x00, // DLL version 0.1.0
    0xa0, 0xa1, 0xa2, 0xa3, 0xa4, 0xa5, 0xa6, 0xa7, // executable fingerprint
    0xa8, 0xa9, 0xaa, 0xab, 0xac, 0xad, 0xae, 0xaf, 0xb0, 0xb1, 0xb2, 0xb3, 0xb4, 0xb5, 0xb6, 0xb7,
    0xb8, 0xb9, 0xba, 0xbb, 0xbc, 0xbd, 0xbe, 0xbf, 0xe5, 0x02, 0x00, 0x00, // layout ID: 741
];

#[test]
fn hello_encoding_matches_the_golden_fixture() {
    assert_eq!(encode_frame(&hello_frame()).unwrap(), HELLO_FRAME_BYTES);
}

#[test]
fn hello_golden_fixture_decodes_to_the_expected_frame() {
    assert_eq!(decode_frame(&HELLO_FRAME_BYTES).unwrap(), hello_frame());
}
